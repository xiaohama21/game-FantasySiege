def svg_bytes(name: str) -> bytes:
    label, geometry = ICONS[name]
    return (
        '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">\n'
        f"  <title>{label}</title>\n"
        f'  <g fill="none" stroke="{PALETTE["ink"]}" stroke-width="1.7" '
        'stroke-linecap="round" stroke-linejoin="round">\n'
        + "\n".join("    " + line for line in geometry.format_map(PALETTE).strip().splitlines())
        + "\n  </g>\n</svg>\n"
    ).encode("utf-8")


def output_directory() -> Path:
    if PROJECT_ROOT.name.casefold() != "fantasysiege" or not (PROJECT_ROOT / "project.godot").is_file():
        raise RuntimeError("This generator must remain inside the FantasySiege project")
    target = PROJECT_ROOT / "assets" / "ui" / "icons"
    if target.resolve() != target:
        raise RuntimeError("The icon output directory must not redirect to another directory")
    return target


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify existing SVG bytes without writing")
    args = parser.parse_args()
    target = output_directory()
    if not args.check:
        target.mkdir(parents=True, exist_ok=True)
    hashes: dict[str, str] = {}
    failures: list[str] = []
    for name in ICONS:
        path = target / (name + ".svg")
        expected = svg_bytes(name)
        if args.check:
            if not path.is_file() or path.read_bytes() != expected:
                failures.append(name)
        else:
            path.write_bytes(expected)
        hashes[name + ".svg"] = hashlib.sha256(expected).hexdigest()
    print("UI_ICONS_COMPLETE " + json.dumps({
        "passed": not failures, "count": len(ICONS), "view_box": [0, 0, 24, 24],
        "scope": "Original native SVG geometry; transparent background; no Godot or raster generation",
        "sha256": hashes, "failures": failures,
    }, ensure_ascii=False))
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
